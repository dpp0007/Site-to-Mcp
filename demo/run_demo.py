"""Drives the REAL MCP server over stdio (same protocol Claude Desktop / Claude Code use) through a chained,
multi-tool trip-planning flow, and writes the actual responses to demo/transcript.md.

    python demo/run_demo.py [YYYY-MM-DD]

Each step's input comes from the previous step's output (search -> pick best -> get details -> prerequisites ...),
so this is multi-step use of several tools, not one scripted call.  Needs TINYFISH_API_KEY.
"""
import asyncio
import json
import pathlib
import sys
import time

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

ROOT = pathlib.Path(__file__).parent.parent
DAY = sys.argv[1] if len(sys.argv) > 1 else "2026-11-14"
log: list[str] = []


async def call(s: ClientSession, name: str, **args):
    t = time.time()
    r = await s.call_tool(name, args)
    text = r.content[0].text if r.content else ""
    secs = time.time() - t
    shown = text if len(text) < 1400 else text[:1400] + "\n... (truncated)"
    log.append(f"### `{name}({', '.join(f'{k}={v!r}' for k, v in args.items())})`  -  {secs:.1f}s"
               f"{'  -  **ERROR**' if r.isError else ''}\n```\n{shown}\n```\n")
    print(f"{name}({args}) {secs:.0f}s error={r.isError}")
    return (None if r.isError else json.loads(text)), text


async def main():
    params = StdioServerParameters(command=sys.executable, args=[str(ROOT / "server.py")])
    async with stdio_client(params) as (r, w), ClientSession(r, w) as s:
        await s.initialize()
        tools = (await s.list_tools()).tools
        log.append("## Tools the client sees\n" + "\n".join(f"- `{t.name}`: {t.description}" for t in tools) + "\n")
        log.append(f"## Scenario\n*I'm visiting New York on {DAY} and want to take an algorithms course at MIT next term. "
                   "Find the course and its prerequisites, something free for kids that day, and Python events I could join.*\n")
        hits, _ = await call(s, "mit_search_courses", query="introduction to algorithms", limit=3)
        best = hits["items"][0]["code"]
        course, _ = await call(s, "mit_get_course", code=best)
        for pre in course["prerequisite_codes"][:2]:
            await call(s, "mit_get_course", code=pre)
        await call(s, "mit_get_course", code="6.9999")  # does not exist -> loud NOT_FOUND
        cats, _ = await call(s, "list_nyc_parks_event_categories")
        kids = next(c["slug"] for c in cats["categories"] if c["slug"] == "kids")
        evs, _ = await call(s, "list_nyc_parks_events", date=DAY, category=kids, limit=3)
        url = next((e["url"] for e in evs["events"] if e["url"]), None)
        if url:
            await call(s, "get_nyc_parks_event", event_url=url)
        await call(s, "list_nyc_parks_events", date=DAY, category="not-a-category")  # BAD_INPUT, tells the agent what to do
        await call(s, "list_python_events", limit=3)
        await call(s, "get_park_conditions", park="abcd")  # unknown park -> NOT_FOUND, no agent credits spent
    (ROOT / "demo" / "transcript.md").write_text(
        "# Demo: multi-step use of several tools over the real MCP protocol\n\n"
        f"Generated by `python demo/run_demo.py {DAY}` - every response below is the server's actual output "
        "(live TinyFish calls), including the deliberate error cases.\n\n" + "\n".join(log), encoding="utf-8")
    print("wrote demo/transcript.md")


asyncio.run(main())
